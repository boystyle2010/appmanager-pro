#!/usr/bin/env python3
"""Công cụ bản dịch AppManager Pro (0.27) — xem TRANSLATING.md.

  python scripts/i18n.py export          # sinh app/static/i18n/en.json (bản mẫu) từ i18n.js + auth.html + notify.py
  python scripts/i18n.py status          # % đã dịch của từng ngôn ngữ
  python scripts/i18n.py missing de      # in các câu (tiếng Anh) mà de.json còn thiếu — dán vào file rồi dịch
  python scripts/i18n.py check           # kiểm tra mọi file: JSON hợp lệ, đủ {chỗ trống}, không có khoá lạ, en.json mới nhất

Nguồn gốc (tiếng Anh + tiếng Việt) nằm trong mã: app/static/js/i18n.js (giao diện), app/templates/auth.html (trang đăng
nhập), app/core/notify.py `T` (tin nhắn thông báo). Ngôn ngữ khác: app/static/i18n/<mã>.json. Cần Node.js để đọc file JS.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
I18N = ROOT / "app" / "static" / "i18n"
SECTIONS = ("ui", "login", "notify")
PH = re.compile(r"\{[A-Za-z_][A-Za-z0-9_]*\}")

_NODE = r"""
const fs = require('fs');
const out = {};
global.window = {}; require(process.argv[1]);
out.ui = window.AMP_I18N;
const html = fs.readFileSync(process.argv[2], 'utf8');
const i = html.indexOf('const dict = {'); const j = html.indexOf('\n      };', i);
out.login = (new Function('return ' + html.slice(i + 'const dict = '.length, j + 8)))();
console.log(JSON.stringify(out));
"""


def sources() -> dict[str, dict[str, dict[str, str]]]:
    """{"en": {"ui": {...}, "login": {...}, "notify": {...}}, "vi": {...}} đọc thẳng từ mã nguồn."""
    if not shutil.which("node"):
        raise SystemExit("Node.js is needed to read app/static/js/i18n.js")
    r = subprocess.run(["node", "-e", _NODE, str(ROOT / "app/static/js/i18n.js"), str(ROOT / "app/templates/auth.html")],
                       capture_output=True, text=True, check=True)
    js = json.loads(r.stdout)
    sys.path.insert(0, str(ROOT))
    from app.core.notify import T  # noqa: E402
    return {lang: {"ui": js["ui"][lang], "login": js["login"][lang], "notify": T[lang]} for lang in ("en", "vi")}


def template(src: dict) -> dict:
    return {"_meta": {"name": "English", "english": "English", "locale": "en-US",
                      "note": "Generated by `python scripts/i18n.py export` — do not edit. Translate a copy (see TRANSLATING.md)."},
            **{s: dict(sorted(src["en"][s].items())) for s in SECTIONS}}


def packs() -> dict[str, dict]:
    out = {}
    for f in sorted(I18N.glob("*.json")):
        if f.stem != "en":
            out[f.stem] = json.loads(f.read_text(encoding="utf-8"))
    return out


def problems(code: str, pack: dict, en: dict) -> list[str]:
    errs = []
    meta = pack.get("_meta") or {}
    for k in ("name", "english", "locale"):
        if not meta.get(k):
            errs.append(f"{code}: _meta.{k} is missing")
    for s in SECTIONS:
        sec = pack.get(s) or {}
        if not isinstance(sec, dict):
            errs.append(f"{code}: '{s}' must be an object"); continue
        for k, v in sec.items():
            if k not in en[s]:
                errs.append(f"{code}.{s}.{k}: unknown key (removed or renamed in English?)"); continue
            src = en[s][k]
            if isinstance(src, list):  # vd weekdays: danh sách cùng độ dài
                if not (isinstance(v, list) and len(v) == len(src) and all(isinstance(x, str) and x for x in v)):
                    errs.append(f"{code}.{s}.{k}: must be a list of {len(src)} texts")
                continue
            if not isinstance(v, str):
                errs.append(f"{code}.{s}.{k}: must be text"); continue
            want, got = sorted(set(PH.findall(src))), sorted(set(PH.findall(v)))
            if want != got:
                errs.append(f"{code}.{s}.{k}: placeholders {got} should be {want}")
    return errs


def main() -> int:
    cmd = sys.argv[1] if len(sys.argv) > 1 else "status"
    src = sources()
    for lang in ("vi",):  # bản gốc: tiếng Việt phải có đủ mọi khoá tiếng Anh
        for s in SECTIONS:
            miss = sorted(set(src["en"][s]) - set(src[lang][s]))
            if miss:
                print(f"vi.{s} is missing: {', '.join(miss[:20])}")
                if cmd == "check":
                    return 1
    en = {s: src["en"][s] for s in SECTIONS}
    if cmd == "export":
        I18N.mkdir(parents=True, exist_ok=True)
        (I18N / "en.json").write_text(json.dumps(template(src), ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"wrote {I18N / 'en.json'} ({sum(len(en[s]) for s in SECTIONS)} strings)")
        return 0
    if cmd == "missing":
        code = sys.argv[2]
        pack = packs().get(code, {})
        out = {s: {k: v for k, v in en[s].items() if k not in (pack.get(s) or {})} for s in SECTIONS}
        print(json.dumps(out, ensure_ascii=False, indent=1))
        return 0
    total = sum(len(en[s]) for s in SECTIONS)
    errs = []
    cur = I18N / "en.json"
    if not cur.exists() or json.loads(cur.read_text(encoding="utf-8")) != template(src):
        errs.append("app/static/i18n/en.json is out of date — run: python scripts/i18n.py export")
    rows = [("en", "English", total), ("vi", "Tiếng Việt", total)]
    for code, pack in packs().items():
        errs += problems(code, pack, en)
        done = sum(len(set(en[s]) & set(pack.get(s) or {})) for s in SECTIONS)
        rows.append((code, (pack.get("_meta") or {}).get("name", "?"), done))
    if cmd == "status":
        for code, name, done in rows:
            print(f"{code:6} {name:22} {done:5}/{total}  {done * 100 // total:3}%")
    for e in errs:
        print("ERROR", e)
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
