// Cài đặt kiểu iOS (0.25.1): tiêu đề lớn, thẻ Chế độ tối, nhóm có nhãn chữ in hoa + giá trị hiện tại, trang Ngôn ngữ,
// thanh "N thay đổi · Huỷ · Lưu" (đếm đúng, Huỷ trả lại, Lưu ghi vào máy chủ). argv: OUT, base URL (admin / Test-Passw0rd!x)
const { chromium } = require('playwright');
const OUT = process.argv[2], B = process.argv[3];
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const R = []; const check = (n, c, d = '') => { R.push(!!c); console.log((c ? 'PASS ' : 'FAIL ') + n + (c ? '' : ' :: ' + d)); };
(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await ctx.request.post(B + '/api/auth/login', { data: { username: 'admin', password: 'Test-Passw0rd!x' }, headers: { Origin: B } });
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message));
  const D = (code) => p.evaluate((c) => (new Function('d', c))(Alpine.$data(document.body)), code);
  await p.goto(B + '/'); await sleep(2500); await D("d.lang = 'vi'; d.dataSetup.open = false");
  await D('d.openSettings()'); await sleep(1500);
  const body = await p.textContent('body');
  check('Home: large title, dark mode card, uppercase group labels', body.includes('Tuỳ chỉnh AppManager theo ý bạn') && body.includes('Chế độ tối')
        && await p.locator('section p.uppercase', { hasText: 'Bảo mật & tài khoản' }).count() === 1);
  check('Rows show the current value (auto-update / 2FA)', body.includes('Kiểm tra mỗi') && body.includes('Xác thực 2 lớp đang tắt'), body.slice(0, 300));
  await p.screenshot({ path: OUT + '/c1-settings-home.png' });
  await p.locator('button', { hasText: 'Chế độ tối' }).click(); await sleep(400);
  check('Dark mode card switches the theme', (await D('return d.theme')) === 'light');
  await p.screenshot({ path: OUT + '/c2-settings-light.png' });
  await p.locator('button', { hasText: 'Chế độ tối' }).click(); await sleep(300);
  await D("d.openSettingsSection('language')"); await sleep(500);
  await p.screenshot({ path: OUT + '/c3-language.png' });
  await p.locator('button', { hasText: 'English' }).click(); await sleep(400);
  check('Language page switches right away', (await D('return d.lang')) === 'en' && (await p.textContent('body')).includes('Applies right away'));
  await p.locator('button', { hasText: 'Tiếng Việt' }).click(); await sleep(300);
  await D("d.openSettingsSection('schedule')"); await sleep(500);
  check('No pending bar before any change', !(await p.locator('text=thay đổi').first().isVisible().catch(() => false)));
  await D('d.settingsForm.auto_update_enabled = !d.settingsForm.auto_update_enabled; d.settingsForm.check_interval_hours = 12'); await sleep(400);
  check('Pending bar counts 2 changes', await p.getByText('2 thay đổi').isVisible());
  await p.screenshot({ path: OUT + '/c4-pending.png' });
  await p.getByRole('button', { name: 'Huỷ', exact: true }).click(); await sleep(300);
  check('Discard restores the saved values', (await D('return d.settingsChanges()')) === 0 && (await D('return d.settingsForm.check_interval_hours')) !== 12);
  await D('d.settingsForm.check_interval_hours = 12'); await sleep(300);
  await p.getByRole('button', { name: 'Lưu', exact: true }).click(); await sleep(1200);
  const saved = await p.evaluate(async () => (await (await fetch('/api/settings')).json()).settings.check_interval_hours);
  check('Save writes to the server and the bar disappears', saved === 12 && (await D('return d.settingsChanges()')) === 0, saved);
  await D("d.settingsModal.tab = 'home'"); await sleep(400);
  check('Home shows the new value', (await p.textContent('body')).includes('mỗi 12 giờ'));
  // Giao diện: full màn hình, tiêu đề ngang nút X, không còn nút (i)
  const geo = await p.evaluate(() => { const el = document.querySelector('.settings-screen'); const r = el.getBoundingClientRect(); return { w: r.width, h: r.height }; });
  check('Settings fill the whole screen', geo.w === 390 && geo.h === 844, JSON.stringify(geo));
  check('No (i) button on the Settings home', (await p.locator('.settings-screen button[title]').count()) === 0);
  await D("d.openSettingsSection('appearance')"); await sleep(500);
  await p.screenshot({ path: OUT + '/c5-appearance.png' });
  await D("d.setUi('accent', 'pink'); d.setUi('text', 'l'); d.setUi('radius', 'crisp'); d.setUi('icons', 'solid'); d.setUi('appIcon', 'emerald')"); await sleep(500);
  const ds = await p.evaluate(() => ({ ...document.documentElement.dataset }));
  check('Appearance previews right away (accent / text size / corners)', ds.accent === 'pink' && ds.text === 'l' && ds.radius === 'crisp', JSON.stringify(ds));
  const sky = await p.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--color-sky-500').trim());
  check('Accent recolors the theme color variables', sky.includes('354'), sky);
  check('Pending bar counts the 5 appearance changes', await p.getByText('5 thay đổi').isVisible());
  await p.screenshot({ path: OUT + '/c6-appearance-pink.png' });
  await p.getByRole('button', { name: 'Huỷ', exact: true }).click(); await sleep(300);
  check('Discard puts the old appearance back', (await p.evaluate(() => document.documentElement.dataset.accent)) === 'sky' && (await D('return d.ui.appIcon')) === 'default');
  await D("d.setUi('accent', 'emerald'); d.setUi('appIcon', 'emerald')"); await sleep(300);
  await p.getByRole('button', { name: 'Lưu', exact: true }).click(); await sleep(600);
  check('Save keeps the appearance on this device', JSON.parse(await p.evaluate(() => localStorage.getItem('amp_ui'))).accent === 'emerald');
  await p.reload(); await sleep(2500);
  const after = await p.evaluate(() => ({ a: document.documentElement.dataset.accent, icon: document.querySelector('link[rel="apple-touch-icon"]').getAttribute('href'), mf: document.querySelector('link[rel="manifest"]').getAttribute('href') }));
  check('After reload: accent + Home Screen icon + manifest icon kept', after.a === 'emerald' && after.icon.includes('icon-emerald') && after.mf.includes('icon=emerald'), JSON.stringify(after));
  const mf = await p.evaluate(async () => (await (await fetch('/manifest.json?icon=emerald')).json()).icons[0].src);
  const bad = await p.evaluate(async () => (await (await fetch('/manifest.json?icon=../x')).json()).icons[0].src);
  const img = await p.evaluate(async () => (await fetch('/assets/icon-emerald.png')).status);
  check('Manifest serves the chosen icon (unknown names fall back)', mf === '/assets/icon-emerald.png' && bad === '/assets/icon.png' && img === 200, mf + ' ' + bad + ' ' + img);
  // Bộ nhớ đệm: trang riêng (thiết bị này + máy chủ)
  await D('d.openSettings()'); await sleep(1000);
  await p.getByText('Bộ nhớ đệm', { exact: true }).click(); await sleep(1200);
  const st = await D('return d.cacheState.stats');
  check('Cache page shows server caches with counts (network, changelogs, SSO, CPU/RAM)', st && st.http && st.updates && st.resources && st.sso, JSON.stringify(st));
  await p.screenshot({ path: OUT + '/c7-cache.png' });
  const rowBtn = (key) => p.locator(`[data-cache="${key}"] button`);
  check('Each cache explains what it is for ("Nên xoá khi")', await p.locator('[data-cache]').count() === 7 && (await p.textContent('body')).includes('Bộ nhớ đệm là gì?'));
  await rowBtn('http').click(); await sleep(400);
  check('Server cache asks for confirmation first', await D('return d.confirmModal.open'));
  await D('d.confirmModal.onConfirm(); d.confirmModal.open = false'); await sleep(1500);
  const st2 = await D('return d.cacheState.stats');
  check('Network cache cleared on the server', st2.http.count === 0, JSON.stringify(st2.http));
  await rowBtn('uireset').click(); await sleep(300); await D('d.confirmModal.onConfirm(); d.confirmModal.open = false'); await sleep(400);
  check('Reset appearance on this device -> defaults', (await p.evaluate(() => document.documentElement.dataset.accent)) === 'sky' && (await p.evaluate(() => localStorage.getItem('amp_ui'))) === null);
  await D("d.setUi('accent', 'emerald')"); await D('d.saveSettings()'); await sleep(500);
  await rowBtn('ui').click();
  await p.waitForURL(/\/(\?r=\d+)?$/, { timeout: 8000 }).catch(() => {}); await sleep(2500);
  const after2 = await p.evaluate(() => ({ url: location.href, me: !!document.querySelector('.glass-header'), accent: document.documentElement.dataset.accent }));
  check('"Clear & reload" reloads the page, keeps the sign-in and the appearance, cleans the address', after2.me && after2.accent === 'emerald' && !after2.url.includes('?r='), JSON.stringify(after2));
  check('No JavaScript errors', !errs.length, errs.join(' | '));
  console.log(`SUMMARY ${R.filter(Boolean).length} / ${R.length}`);
  await b.close();
})();
